CREATE TABLE sys_role (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  name_zh VARCHAR(80) NOT NULL,
  name_en VARCHAR(80) NOT NULL,
  name_vi VARCHAR(80) NOT NULL,
  remark VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sys_user (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(120) NOT NULL,
  real_name VARCHAR(80) NOT NULL,
  email VARCHAR(120),
  phone VARCHAR(30),
  avatar VARCHAR(255),
  remark VARCHAR(255),
  last_login_at TIMESTAMPTZ,
  role_id INTEGER NOT NULL REFERENCES sys_role(id),
  status TEXT NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sys_menu (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id INTEGER NOT NULL DEFAULT 0,
  code VARCHAR(60) NOT NULL UNIQUE,
  path VARCHAR(120) NOT NULL,
  icon VARCHAR(40),
  name_zh VARCHAR(80) NOT NULL,
  name_en VARCHAR(80) NOT NULL,
  name_vi VARCHAR(80) NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_sys_menu_parent_sort ON sys_menu (parent_id, sort_order, id);

CREATE TABLE sys_role_menu (
  role_id INTEGER NOT NULL REFERENCES sys_role(id) ON DELETE CASCADE,
  menu_id INTEGER NOT NULL REFERENCES sys_menu(id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, menu_id)
);

CREATE TABLE sys_password_reset (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
  username VARCHAR(50) NOT NULL,
  email VARCHAR(120),
  code_hash VARCHAR(120) NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  used SMALLINT NOT NULL DEFAULT 0 CHECK (used IN (0, 1)),
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_username_created ON sys_password_reset (username, created_at);

CREATE TABLE sys_login_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL,
  ip VARCHAR(80),
  user_agent VARCHAR(255),
  success SMALLINT NOT NULL CHECK (success IN (0, 1)),
  message VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_login_log_created ON sys_login_log (created_at);

CREATE TABLE sys_operation_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER,
  username VARCHAR(50),
  module VARCHAR(60) NOT NULL,
  action VARCHAR(60) NOT NULL,
  detail VARCHAR(500),
  ip VARCHAR(80),
  method VARCHAR(10),
  path VARCHAR(160),
  status INTEGER,
  duration_ms INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_operation_log_created ON sys_operation_log (created_at);

CREATE TABLE term_category (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_zh VARCHAR(100) NOT NULL,
  name_en VARCHAR(100) NOT NULL,
  name_vi VARCHAR(100) NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_term_category_name_zh UNIQUE (name_zh)
);
CREATE INDEX idx_term_category_sort ON term_category (sort_order, id);

CREATE TABLE railway_term (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id INTEGER NOT NULL REFERENCES term_category(id),
  term_zh VARCHAR(160) NOT NULL,
  term_en VARCHAR(160) NOT NULL,
  term_vi VARCHAR(160) NOT NULL,
  pinyin VARCHAR(200),
  difficulty TEXT NOT NULL DEFAULT 'easy' CHECK (difficulty IN ('easy', 'medium', 'hard')),
  definition_zh TEXT,
  definition_en TEXT,
  definition_vi TEXT,
  example_zh TEXT,
  example_en TEXT,
  example_vi TEXT,
  status TEXT NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
  created_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_railway_term_term_zh UNIQUE (term_zh)
);
CREATE INDEX idx_railway_term_category ON railway_term (category_id, id);
CREATE INDEX idx_railway_term_status ON railway_term (status, difficulty);

CREATE TABLE practice_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES sys_user(id),
  practice_type VARCHAR(40) NOT NULL,
  category_id INTEGER REFERENCES term_category(id),
  difficulty VARCHAR(20),
  total_count INTEGER NOT NULL CHECK (total_count >= 0),
  correct_count INTEGER NOT NULL CHECK (correct_count >= 0 AND correct_count <= total_count),
  score NUMERIC(5,2) NOT NULL CHECK (score >= 0 AND score <= 100),
  duration_seconds INTEGER NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_practice_record_user_created ON practice_record (user_id, created_at DESC);

CREATE TABLE practice_answer (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id BIGINT NOT NULL REFERENCES practice_record(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES railway_term(id),
  question_type VARCHAR(40) NOT NULL,
  question_text VARCHAR(255) NOT NULL,
  user_answer VARCHAR(255),
  correct_answer VARCHAR(255) NOT NULL,
  is_correct SMALLINT NOT NULL CHECK (is_correct IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_practice_answer_record ON practice_answer (record_id, id);

CREATE TABLE wrong_question (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES railway_term(id) ON DELETE CASCADE,
  wrong_count INTEGER NOT NULL DEFAULT 1 CHECK (wrong_count > 0),
  last_wrong_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uniq_user_term UNIQUE (user_id, term_id)
);

CREATE TABLE favorite_term (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES railway_term(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uniq_fav UNIQUE (user_id, term_id)
);

CREATE TABLE agent_model (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL UNIQUE,
  label VARCHAR(120) NOT NULL,
  family VARCHAR(60),
  param_size VARCHAR(20),
  tier TEXT NOT NULL DEFAULT 'recommended' CHECK (tier IN ('light', 'recommended', 'advanced', 'too_large')),
  description_zh VARCHAR(255),
  is_default SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
  status TEXT NOT NULL DEFAULT 'enabled' CHECK (status IN ('enabled', 'disabled')),
  pulled_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE agent_session (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES sys_user(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  model VARCHAR(120),
  message_count INTEGER NOT NULL DEFAULT 0 CHECK (message_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_user_updated ON agent_session (user_id, updated_at DESC);

CREATE TABLE agent_message (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES agent_session(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system')),
  content TEXT,
  model VARCHAR(120),
  tokens INTEGER NOT NULL DEFAULT 0 CHECK (tokens >= 0),
  duration_ms INTEGER NOT NULL DEFAULT 0 CHECK (duration_ms >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_session_created ON agent_message (session_id, created_at);

CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_sys_user_updated_at BEFORE UPDATE ON sys_user FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_railway_term_updated_at BEFORE UPDATE ON railway_term FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_agent_session_updated_at BEFORE UPDATE ON agent_session FOR EACH ROW EXECUTE FUNCTION set_updated_at();
